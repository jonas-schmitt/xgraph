def words(text: str) -> set[str]:
    """The text's words, case-folded."""
    return set(_WORD.findall(_lexical_text(text).casefold()))


def _lexical_text(text: str) -> str:
    """Optional schema adaptation for ranking only; executable labels stay unchanged."""
    schema = os.environ.get("XGRAPH_LEXICAL_SCHEMA", "")
    if schema not in ("", "freebase"):
        raise ValueError(f"unknown XGRAPH_LEXICAL_SCHEMA: {schema!r}")
    return text.replace("_", " ").replace(".", " ") if schema else text


def question_overlap(names: list[str], question: set[str]) -> float:
    """The largest share of a name's words (a relation's labels and aliases) that the
    question's words hold."""
    best = 0.0
    for name in names:
        own = words(name)
        if own:
            best = max(best, len(own & question) / len(own))
    return best


def stem(word: str) -> str:
    """A crude stem of a case-folded word, so that `citizen` meets `country of
    citizenship` and `born` meets `place of birth`: a few synonyms, then one common
    suffix stripped (keeping three letters), then the first five letters."""
    word = _SYNONYMS.get(word, word)
    for suffix in _SUFFIXES:
        if word.endswith(suffix) and len(word) - len(suffix) >= 3:
            word = word[: -len(suffix)]
            break
    return word[:5]


def content_stems(text: str, drop: set[str] = frozenset()) -> set[str]:
    """The stems of the text's words that are not stopwords, nor in drop."""
    found = _WORD.findall(_lexical_text(text).casefold())
    return {stem(w) for w in found if w not in _STOPWORDS and w not in drop}


def answer_head(question: str) -> str | None:
    """The question's answer head: the word after a leading which or what (`country` in
    "In which country is ...", `capital` in "What is the capital of ..."), else who,
    whom, whose, or where itself; None for a question that starts otherwise."""
    found = _HEAD.match(question)
    if not found:
        return None
    wh, word = found.group(1).casefold(), (found.group(2) or "").casefold()
    if wh in _WH_HEADS:
        return wh
    return word if word and word not in _STOPWORDS else None


def _head_classes(head: str | None) -> set[str]:
    from xgraph.walk import COARSE_CLASSES

    if head is None:
        return set()
    if head in _HEAD_CLASSES:
        return set(_HEAD_CLASSES[head])
    return {c for c in COARSE_CLASSES.values() if c.split()[-1] == head}


def shortlist_scores(record: dict) -> list[float]:
    """Each candidate's shortlist score, without gold, from the question and its relation
    labels and coarse class: the share of the question's content words (its words but
    stopwords and the start's) its labels hold; a bonus when the answer head's word ends
    its last label, and a smaller one when its coarse class is one the head asks for
    (a person for who, a place for where); less the share of its label words the question
    does not hold and its difference in length from the original plan (weights:
    SHORTLIST_WEIGHTS)."""
    weight = SHORTLIST_WEIGHTS
    question = record["question"]
    start = set(_WORD.findall((record["start"] or "").casefold()))
    content, asked = content_stems(question, start), content_stems(question)
    head = answer_head(question)
    head_stem = stem(head) if head and head not in _WH_HEADS else None
    classes = _head_classes(head)
    candidates = record["candidates"]
    written = len(candidates[0]["relations"]) if candidates else 0
    scores = []
    for candidate in candidates:
        labels: set[str] = set()
        for label in candidate["relations"]:
            labels |= content_stems(label)
        coverage = len(content & labels) / len(content) if content else 0.0
        unasked = len(labels - asked) / len(labels) if labels else 0.0
        last = content_stems(candidate["relations"][-1]) if candidate["relations"] else set()
        score = weight["coverage"] * coverage - weight["unasked"] * unasked
        score += weight["head"] * (head_stem is not None and head_stem in last)
        score += weight["class"] * (candidate["class"] in classes)
        score -= weight["length"] * abs(len(candidate["relations"]) - written)
        scores.append(score)
    return scores


def shortlisted(record: dict, size: int) -> list[int]:
    """The shortlist of size plans: the original (candidate 0), then the size - 1
    alternatives of the highest shortlist score (shortlist_scores), earlier candidates
    first among equals; all of them when there are fewer."""
    if size < 2:
        raise ValueError(f"a shortlist holds at least 2 plans, not {size}")
    if not record["candidates"]:
        return []
    scores = shortlist_scores(record)
    ranked = sorted(range(1, len(scores)), key=lambda k: (-scores[k], k))
    return [0, *ranked[: size - 1]]


def ranked_choice(record: dict) -> int:
    """The candidate of the highest shortlist score, the original among equals."""
    if not record["candidates"]:
        return 0
    scores = shortlist_scores(record)
    return max(range(len(scores)), key=lambda k: (scores[k], -k))


def alternatives(
    relations: list[str], offered: list[list[str]] | None = None, limit: int | None = None
) -> list[tuple[str, list[str]]]:
    """The candidate plans of a written plan, (kind, relation labels), the original first,
    then its proper prefixes (shortest first), single deletions, and, with offered (the
    relation labels to try at each position 0..len(relations), most wanted first), single
    substitutions (at positions before the end) and insertions; each plan once, none
    empty or longer than limit."""
    plans: list[tuple[str, list[str]]] = [("original", list(relations))]
    plans += [("prefix", relations[:k]) for k in range(1, len(relations))]
    plans += [("deletion", relations[:i] + relations[i + 1 :]) for i in range(len(relations))]
    for i, labels in enumerate(offered or []):
        for label in labels:
            if i < len(relations):
                plans.append(("substitution", [*relations[:i], label, *relations[i + 1 :]]))
            plans.append(("insertion", [*relations[:i], label, *relations[i:]]))
    seen: set[tuple[str, ...]] = set()
    kept = []
    for kind, plan in plans:
        key = tuple(plan)
        if plan and key not in seen and (limit is None or len(plan) <= limit):
            seen.add(key)
            kept.append((kind, plan))
    return kept


class Repairer:
    """A path-mode answer's candidate plans, executed by matched execution (see the
    module docstring)."""

    def __init__(self, executor, store, relation_rows, edits: int = DEFAULT_EDITS, stores=None):
        from xgraph.wikidata import relation_names

        self._executor, self._store, self._stores = executor, store, stores or {}
        self._edits = edits
        names = relation_names(relation_rows)
        self._names = names
        self._label = {prop: label for prop, label, kind in relation_rows if kind == "label"}
        self._named: dict[str, list[str]] = {}
        for prop, labels in names.items():
            for label in labels:
                self._named.setdefault(label, []).append(prop)
        self._classes: dict = {}

    def candidates(
        self,
        question: str,
        start: str,
        relations: list[str],
        anchor: list[str] | None = None,
        version: str | None = None,
    ) -> tuple[list[dict], int]:
        """The candidates that reach something, the original first, and how many were
        dropped as empty."""
        from xgraph.oracle import MAX_PATH_RELATIONS

        relations = relations[:MAX_PATH_RELATIONS]
        # Edited candidates are fresh plans. Only the original retains frontier
        # selections; reusing them after an edit can select an unrelated frontier.
        fresh = list(relations)
        offered = None
        if self._edits:
            asked = words(question)
            offered = []
            for i in range(len(relations) + 1):
                found = self._executor.frontier_relations(start, fresh[:i], anchor, version)
                written = set(self._named.get(relations[i], ())) if i < len(relations) else set()
                ranked = sorted(
                    (prop for prop, _ in found if prop in self._label),
                    key=lambda p: -question_overlap(self._names.get(p, [self._label[p]]), asked),
                )  # stable: most frontier edges, then index order, break ties
                labels = [self._label[p] for p in ranked if p not in written]
                offered.append(labels[: self._edits])
        kept, empty = [], 0
        plans = alternatives(fresh, offered, MAX_PATH_RELATIONS)
        if not fresh and getattr(relations, "selections", {}):
            plans.insert(0, ("original", relations))
        for kind, plan in plans:
            if kind == "original":
                plan = relations
            path = self._executor.execute(start, plan, anchor=anchor, version=version)
            if not path.reached and kind != "original":
                empty += 1
                continue
            kept.append(self._candidate(kind, plan, path, version))
        return kept, empty

    def _candidate(self, kind: str, plan: list[str], path, version: str | None) -> dict:
        from xgraph.walk import UNKNOWN, frontier_class

        read = self._stores[version] if version else self._store
        items = [int(e[1:]) for e in path.reached]
        found = frontier_class(read, items, self._classes, coarse=True) if items else None
        return {
            "kind": kind,
            "relations": plan,
            **({"selections": dict(plan.selections)} if getattr(plan, "selections", {}) else {}),
            "properties": [sorted(self._named.get(r, []), key=lambda p: int(p[1:])) for r in plan],
            "reached": len(path.reached),
            "endpoint": path.answer,
            "answer": read.label(int(path.answer[1:])) if path.answer else None,
            "class": found or UNKNOWN,
        }


def plan_text(start: str, relations: list[str]) -> str:
    return "⟦ " + " · ".join([start, *relations]) + "⟧"


def _observation(candidate: dict, observe: str) -> str:
    count = f"{candidate['reached']} {'entity' if candidate['reached'] == 1 else 'entities'}"
    if observe == "count":
        return f" → {count}"
    if observe == "types":
        return f" → ⟨{candidate['class']}⟩, {count}"
    return ""


def _plans(question: str, start: str, shown: list[dict], observe: str) -> str:
    lines = [
        f"{n}. {plan_text(start, c['relations'])}{_observation(c, observe)}"
        for n, c in enumerate(shown, start=1)
    ]
    return f"Question: {question}\n\nPlans:\n" + "\n".join(lines)


def _demonstration(demo: dict, observe: str) -> list[dict]:
    example = [
        {"relations": rels, "class": cls, "reached": n} for rels, cls, n in demo["plans"]
    ]  # fmt: skip
    return [
        {"role": "user", "content": _plans(demo["question"], demo["start"], example, observe)},
        {"role": "assistant", "content": str(demo["choice"])},
    ]


def verifier_request(
    record: dict, observe: str = "none", seed: int = SEED, shortlist: int | None = None
) -> dict | None:
    """The verifier's chat request for a candidates record (see the module docstring),
    None for a question with fewer than two candidates. `shown` lists the candidates'
    positions in the order they are numbered. With shortlist, only the shortlist of
    that many plans (shortlisted) is numbered, and the reply 0 keeps the original;
    `shortlist` records the size."""
    if observe not in OBSERVATIONS:
        raise ValueError(f"unknown observation {observe!r}; expected one of {OBSERVATIONS}")
    candidates = record["candidates"]
    if len(candidates) < 2:
        return None
    if shortlist is None:
        shown = list(range(len(candidates)))
        prompt, demos = VERIFIER_PROMPT, [DEMONSTRATION]
    else:
        shown = shortlisted(record, shortlist)
        prompt, demos = SHORTLIST_PROMPT, [DEMONSTRATION, KEEP_DEMONSTRATION]
    random.Random(f"{seed}:{record['id']}").shuffle(shown)
    messages = [{"role": "system", "content": prompt.format(observed=OBSERVED[observe])}]
    for demo in demos:
        messages += _demonstration(demo, observe)
    asked = _plans(record["question"], record["start"], [candidates[k] for k in shown], observe)
    messages.append({"role": "user", "content": asked})
    request = {"id": record["id"], "messages": messages, "shown": shown, "observe": observe}
    if shortlist is not None:
        request["shortlist"] = shortlist
    return request


def parse_choice(text: str, options: int, keep: bool = False) -> int | None:
    """The plan number a reply names (its first number, 1 to options, or with keep also
    0), else None."""
    found = _NUMBER.search(text)
    if not found:
        return None
    number = int(found.group())
    return number if (0 if keep else 1) <= number <= options else None


def rule_choice(record: dict, rule: str) -> int:
    """The candidate a deterministic rule chooses (see the module docstring)."""
    candidates = record["candidates"]
    if rule not in RULES:
        raise ValueError(f"unknown rule {rule!r}; expected one of {RULES}")
    if rule == "original" or not candidates:
        return 0
    if rule == "shortest":
        reaching = [k for k, c in enumerate(candidates) if c["reached"]] or [0]
        return min(reaching, key=lambda k: (len(candidates[k]["relations"]), k))
    stopped = [
        k
        for k, c in enumerate(candidates)
        if c["kind"] in ("original", "prefix") and c["reached"] == 1
    ]
    return max(stopped, key=lambda k: (len(candidates[k]["relations"]), -k), default=0)


def chosen_record(record: dict, choice: int, how: str) -> dict:
    """The record a choice delivers: path mode's own for the original, else the chosen
    candidate's path span and delivered answer."""
    candidate = record["candidates"][choice] if record["candidates"] else None
    if choice == 0 or candidate is None:
        text = record["text"]
    else:
        text = plan_text(record["start"], candidate["relations"]) + "."
        text += f"\nAnswer: ⟦ {candidate['answer']}⟧" if candidate["answer"] else ""
    repaired = {"chosen": choice, "how": how}
    if candidate is not None:
        repaired |= {"kind": candidate["kind"], "relations": candidate["relations"]}
    return {"id": record["id"], "arm": "repair", "text": text, "repair": repaired}


def select(records: list[dict], requests: dict[str, dict], verdicts: dict[str, str]) -> list[dict]:
    """Each question's record under the verifier's choice; the original where it was
    not asked or its reply names no plan of the list."""
    chosen = []
    for record in records:
        request = requests.get(record["id"])
        if request is None:
            chosen.append(chosen_record(record, 0, "alone"))
            continue
        keep = bool(request.get("shortlist"))
        number = parse_choice(verdicts.get(record["id"], ""), len(request["shown"]), keep)
        if number is None:
            chosen.append(chosen_record(record, 0, "unparsed"))
        elif number == 0:
            chosen.append(chosen_record(record, 0, "kept"))
        else:
            chosen.append(chosen_record(record, request["shown"][number - 1], "verifier"))
    return chosen


def replayed_request(
    request: dict | None, qid: str, start: str, relations: list[str], *, span: str | None = None
) -> dict:
    """A path-mode request with the plan ⟦ start · relation · ...⟧ as a final assistant
    message the engine replays (see the module docstring)."""
    if request is None:
        raise ValueError(f"question {qid!r} has no path-mode request to deliver")
    if request["messages"] and request["messages"][-1]["role"] == "assistant":
        raise ValueError(f"the path-mode request {qid!r} already ends with a prefill")
    span = span if span is not None else plan_text(start, relations)
    return {
        **request,
        "messages": [*request["messages"], {"role": "assistant", "content": span}],
        "prefill_replay": True,
    }


def delivery_requests(
    records: list[dict], selected: list[dict], requests: dict[str, dict], every: bool = False
) -> list[dict]:
    """For each selected record whose chosen candidate is not the original (with every,
    also each whose original reaches something), its path-mode request with the chosen
    plan as a final assistant message the engine replays (see the module docstring);
    records are the candidates records, for the plans' start and reach."""
    by_id = {r["id"]: r for r in records}
    delivered = []
    for row in selected:
        repaired, record = row["repair"], by_id.get(row["id"])
        if record is None:
            raise ValueError(f"the selected question {row['id']!r} has no candidates record")
        if repaired["chosen"] == 0:
            original = record["candidates"][0] if record["candidates"] else None
            if not (every and original and original["reached"]):
                continue
        request = requests.get(row["id"])
        delivered.append(
            replayed_request(request, row["id"], record["start"], repaired["relations"])
        )
    return delivered


def executed_delivery_requests(executed: list[dict], requests: dict[str, dict]) -> list[dict]:
    """For each record of matched execution (python -m xgraph.programs execute --matched)
    with a plan, its path-mode request with that plan, the labels the executor read, as a
    final assistant message the engine replays (see the module docstring)."""
    delivered = []
    for row in executed:
        if "plan" not in row:
            raise ValueError(
                f"the record {row['id']!r} has no plan: execute it with programs execute --matched"
            )
        if row["plan"] is not None:
            plan = row["plan"]
            request = requests.get(row["id"])
            span = None
            if plan.get("selections"):
                from xgraph.programs import parse_path, record_path

                wanted = record_path(row)
                for match in re.finditer(r"⟦[^⟧]*·[^⟧]*⟧", row.get("text", "")):
                    parsed = parse_path(match.group())
                    if parsed == wanted and parsed[1].selections == wanted[1].selections:
                        span = match.group()
                        break
                if span is None:
                    raise ValueError(
                        f"selected plan {row['id']!r} needs its original observed span for replay"
                    )
            delivered.append(
                replayed_request(request, row["id"], plan["start"], plan["relations"], span=span)
            )
    return delivered


def _generated(qid: str, request: dict, generated: dict[str, dict]) -> dict:
    """The generated record of a delivered request, which starts with its replayed plan."""
    record = generated.get(qid)
    if record is None:
        raise ValueError(f"the delivered question {qid!r} has no generated record")
    span = request["messages"][-1]["content"]
    if not record["text"].startswith(span):
        raise ValueError(f"the generated record of {qid!r} does not start with its plan {span!r}")
    return record


def merged_records(
    selected: list[dict], delivered: dict[str, dict], generated: dict[str, dict]
) -> list[dict]:
    """One record per selected record: the generated record for a delivered question, the
    selected record (path mode's own) otherwise (see the module docstring)."""
    rows = []
    for row in selected:
        request = delivered.get(row["id"])
        if request is None:
            rows.append({**row, "repair": {**row["repair"], "delivery": "path mode"}})
            continue
        record = _generated(row["id"], request, generated)
        repaired = {**row["repair"], "delivery": "engine", "executor_text": row["text"]}
        rows.append({**record, "arm": "repair", "repair": repaired})
    return rows


def merged_executed(
    executed: list[dict], delivered: dict[str, dict], generated: dict[str, dict]
) -> list[dict]:
    """One record per record of matched execution: the generated record for a delivered
    question, with the executed record's arm, plan, and reach, its text as executor_text,
    and `delivery: engine`; the executed record with `delivery: executor` otherwise."""
    rows = []
    for row in executed:
        request = delivered.get(row["id"])
        if request is None:
            rows.append({**row, "delivery": "executor"})
            continue
        record = _generated(row["id"], request, generated)
        kept = {key: row[key] for key in ("arm", "plan", "reached") if key in row}
        rows.append({**record, **kept, "delivery": "engine", "executor_text": row["text"]})
    return rows


def hops(complexity: str) -> str:
    found = re.search(r"(\d+)-hop", complexity)
    return f"{found.group(1)}-hop" if found else "unknown"


def oracle(
    records: list[dict],
    answers: dict[str, str],
    groups: dict[str, str],
    shortlists: list[int] | None = None,
) -> dict:
    """MINTQA's measure over the questions of answers: whether any candidate's answer or
    path mode's own contains the dataset's answer, whether the original's delivered
    answer under matched execution does (`original_matched`; path mode's own answer is the
    model's choice among the entities reached), and each rule's accuracy (RULES), overall
    and per group; with shortlists, `shortlist` holds each size's shortlist_oracle."""
    from xgraph.mintqa_bench import answer_contains

    by_id = {r["id"]: r for r in records}

    def right(qid: str) -> dict[str, bool]:
        record = by_id.get(qid)
        gold = answers[qid]
        if record is None or replay_failure(record):
            return dict.fromkeys(ORACLE, False)
        said = [c["answer"] for c in record["candidates"]] + [record.get("answer")]
        row = {"any_candidate": any(answer_contains(a, gold) for a in said)}
        first = record["candidates"][0]["answer"] if record["candidates"] else None
        row["original_matched"] = answer_contains(first, gold)
        for rule in RULES:
            choice = rule_choice(record, rule)
            if choice == 0:
                row[rule] = answer_contains(record.get("answer"), gold)
            else:
                row[rule] = answer_contains(record["candidates"][choice]["answer"], gold)
        return row

    rows = {qid: right(qid) for qid in answers}

    def share(ids: list[str]) -> dict:
        tally: dict = {"questions": len(ids)}
        for key in ORACLE:
            tally[key] = sum(rows[q][key] for q in ids) / len(ids) if ids else 0.0
        return tally

    split: dict[str, list[str]] = {}
    for qid in rows:
        split.setdefault(groups.get(qid, "unknown"), []).append(qid)
    result = {"all": share(list(rows)), "by_group": {g: share(i) for g, i in sorted(split.items())}}
    if shortlists:
        result["shortlist"] = {
            str(size): shortlist_oracle(records, answers, groups, size) for size in shortlists
        }
    return result


def shortlist_oracle(
    records: list[dict], answers: dict[str, str], groups: dict[str, str], size: int
) -> dict:
    """MINTQA's measure for a shortlist of size plans (shortlisted), over the questions of
    answers, overall and per group: `oracle`, the share whose answer a choice within the
    shortlist can deliver (path mode's own for the original, the executed answer for
    another plan); `recoverable`, the number whose own answer is wrong where some
    alternative's is right, and `kept` (`kept_share`), those of them with a right
    alternative in the shortlist; `ranked`, the accuracy of choosing the candidate of the
    highest shortlist score directly (ranked_choice; the same for every size)."""
    from xgraph.mintqa_bench import answer_contains

    by_id = {r["id"]: r for r in records}

    def row(qid: str) -> dict[str, bool]:
        record, gold = by_id.get(qid), answers[qid]
        if record is None or replay_failure(record):
            return {"oracle": False, "recoverable": False, "kept": False, "ranked": False}
        candidates = record["candidates"]
        own = answer_contains(record.get("answer"), gold)
        right = [
            k for k in range(1, len(candidates)) if answer_contains(candidates[k]["answer"], gold)
        ]
        inside = bool(set(right) & set(shortlisted(record, size)))
        choice = ranked_choice(record)
        ranked = own if choice == 0 else choice in right
        recoverable = not own and bool(right)
        return {
            "oracle": own or inside,
            "recoverable": recoverable,
            "kept": recoverable and inside,
            "ranked": ranked,
        }

    rows = {qid: row(qid) for qid in answers}

    def tally(ids: list[str]) -> dict:
        recoverable = sum(rows[q]["recoverable"] for q in ids)
        kept = sum(rows[q]["kept"] for q in ids)
        return {
            "questions": len(ids),
            "oracle": sum(rows[q]["oracle"] for q in ids) / len(ids) if ids else 0.0,
            "recoverable": recoverable,
            "kept": kept,
            "kept_share": kept / recoverable if recoverable else 0.0,
            "ranked": sum(rows[q]["ranked"] for q in ids) / len(ids) if ids else 0.0,
        }

    split: dict[str, list[str]] = {}
    for qid in rows:
        split.setdefault(groups.get(qid, "unknown"), []).append(qid)
    return {"all": tally(list(rows)), "by_group": {g: tally(i) for g, i in sorted(split.items())}}


def _shortlist_size(text: str) -> int:
    size = int(text)
    if size < 2:
        raise argparse.ArgumentTypeError(f"a shortlist holds at least 2 plans, not {size}")
    return size


def _load(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as lines:
        return [json.loads(line) for line in lines if line.strip()]


def _write(path: Path, rows) -> int:
    n = 0
    with path.open("w", encoding="utf-8") as out:
        for row in rows:
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
            n += 1
    return n


def main(argv: list[str] | None = None) -> None:
    from xgraph.cost import StageTimer
    from xgraph.provenance import provenance

    parser = argparse.ArgumentParser(prog="python -m xgraph.repair", description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    build = commands.add_parser("candidates", help="candidate plans, executed")
    build.add_argument("--outputs", type=Path, required=True, help="path-mode records (JSONL)")
    build.add_argument("--questions", type=Path, required=True, help="questions (JSON)")
    build.add_argument("--db", type=Path, required=True, help="KG store (xgraph.toolkg)")
    build.add_argument("--index", type=Path, required=True, help="the KG index path mode read")
    build.add_argument("--tokenizer", type=Path, required=True, help="its served tokenizer")
    build.add_argument("--relations", type=Path, required=True, help="relation_labels.jsonl")
    build.add_argument(
        "--edits",
        type=int,
        default=DEFAULT_EDITS,
        help="relations tried per position for substitutions and insertions (0: none)",
    )
    build.add_argument("--start-rank", choices=("degree", "sitelinks"), default="degree")
    build.add_argument("--unquoted-starts", action="store_true")
    build.add_argument("--kg-versions", type=Path, help="a KG version file (xgraph.kgversions)")
    build.add_argument(
        "--requests", type=Path, help="the outputs' requests, for their kg_version and anchor"
    )
    build.add_argument("--out", type=Path, required=True, help="candidates (JSONL)")
    ask = commands.add_parser("requests", help="the verifier's chat requests")
    ask.add_argument("--candidates", type=Path, required=True)
    ask.add_argument("--observe", choices=OBSERVATIONS, default="none")
    ask.add_argument("--seed", type=int, default=SEED, help="the candidates' shown order")
    ask.add_argument("--trigger-rule", type=Path, help="frozen selective rule JSON")
    ask.add_argument("--family", help="family entry in --trigger-rule")
    ask.add_argument(
        "--trigger-outputs", type=Path, help="original outputs, for explicit path_logprob"
    )
    ask.add_argument(
        "--shortlist",
        type=_shortlist_size,
        metavar="K",
        help="number only the original and the K - 1 best-ranked other plans, with 0 to keep",
    )
    ask.add_argument("--out", type=Path, required=True)
    choose = commands.add_parser("select", help="records with the chosen candidates")
    choose.add_argument("--candidates", type=Path, required=True)
    choose.add_argument("--requests", type=Path, help="the verifier's requests")
    choose.add_argument("--verdicts", type=Path, help="the verifier's replies (xgraph.generate)")
    choose.add_argument("--rule", choices=RULES, help="choose by a rule instead of replies")
    choose.add_argument("--out", type=Path, required=True)
    give = commands.add_parser("deliver", help="path-mode requests that replay chosen plans")
    give.add_argument("--candidates", type=Path, help="with --selected: the candidates")
    give.add_argument("--selected", type=Path, help="select's records")
    give.add_argument(
        "--all", action="store_true", help="with --selected: the originals that reach something too"
    )
    give.add_argument(
        "--executed",
        type=Path,
        help="instead of --selected: matched execution's records (programs execute --matched)",
    )
    give.add_argument("--requests", type=Path, required=True, help="the path-mode requests")
    give.add_argument("--out", type=Path, required=True, help="requests (xgraph.generate)")
    join = commands.add_parser("merge", help="the engine's answers for the delivered plans")
    chosen = join.add_mutually_exclusive_group(required=True)
    chosen.add_argument("--selected", type=Path, help="select's records")
    chosen.add_argument("--executed", type=Path, help="matched execution's records")
    join.add_argument("--delivered", type=Path, required=True, help="deliver's requests")
    join.add_argument("--generated", type=Path, required=True, help="their generated records")
    join.add_argument("--out", type=Path, required=True)
    check = commands.add_parser("oracle", help="MINTQA: candidate coverage and the rules")
    check.add_argument("--candidates", type=Path, required=True)
    check.add_argument("--questions", type=Path, required=True, help="questions.json (all)")
    check.add_argument("--split", action="append", required=True, help="<ti|pop>=<file>")
    check.add_argument(
        "--shortlist",
        type=_shortlist_size,
        action="append",
        metavar="K",
        help="also the oracle within a shortlist of K plans (repeatable)",
    )
    check.add_argument("--out", type=Path, required=True)
    selective = commands.add_parser("selective", help="offline cross-fitted selective verification")
    selective.add_argument(
        "--manifest", type=Path, required=True, help="family artifacts and MINTQA data"
    )
    selective.add_argument("--out", type=Path, required=True, help="evaluation report JSON")
    selective.add_argument(
        "--freeze", type=Path, required=True, help="frozen per-family rules JSON"
    )
    args = parser.parse_args(argv)
    if args.command == "selective":
        from xgraph.selective_eval import evaluate

        evaluate(args.manifest, args.out, args.freeze)
        return
    timer = StageTimer()

    if args.command == "candidates":
        summary = _candidates(args)
        inputs = [args.outputs, args.questions, args.relations, args.index / "kg-index.json"]
    elif args.command == "requests":
        from xgraph.selective import features, load_rule, triggered

        if bool(args.trigger_rule) != bool(args.family):
            parser.error("requests needs --trigger-rule and --family together")
        if args.trigger_outputs and not args.trigger_rule:
            parser.error("--trigger-outputs needs --trigger-rule and --family")
        rule = load_rule(args.trigger_rule, args.family) if args.trigger_rule else None
        probabilities = None
        if args.trigger_outputs:
            probabilities = {}
            with args.trigger_outputs.open(encoding="utf-8") as lines:
                for line in lines:
                    if not line.strip():
                        continue
                    record = json.loads(line)
                    if record["id"] in probabilities:
                        raise ValueError(f"duplicate original output {record['id']!r}")
                    probabilities[record["id"]] = {"path_logprob": record.get("path_logprob")}
        counts = {"questions": 0}

        def asked():
            with args.candidates.open(encoding="utf-8") as lines:
                for line in lines:
                    if not line.strip():
                        continue
                    record = json.loads(line)
                    counts["questions"] += 1
                    if probabilities is not None and record["id"] not in probabilities:
                        raise ValueError(f"question {record['id']!r} has no original output")
                    output = probabilities[record["id"]] if probabilities is not None else None
                    request = verifier_request(record, args.observe, args.seed, args.shortlist)
                    if request is not None and (
                        rule is None or triggered(features(record, request["shown"], output), rule)
                    ):
                        yield request

        count = _write(args.out, asked())
        summary = {
            **counts,
            "requests": count,
            "observe": args.observe,
            "shortlist": args.shortlist,
            "trigger_rule": rule,
        }
        inputs = [args.candidates] + ([args.trigger_rule] if args.trigger_rule else [])
        if args.trigger_outputs:
            inputs.append(args.trigger_outputs)
    elif args.command == "select":
        records = _load(args.candidates)
        if args.rule:
            rows = [chosen_record(r, rule_choice(r, args.rule), args.rule) for r in records]
            inputs = [args.candidates]
        elif args.requests and args.verdicts:
            requests = {r["id"]: r for r in _load(args.requests)}
            verdicts = {r["id"]: record_text(r) for r in _load(args.verdicts)}
            rows = select(records, requests, verdicts)
            inputs = [args.candidates, args.requests, args.verdicts]
        else:
            parser.error("select needs --rule, or --requests and --verdicts")
        _write(args.out, rows)
        how: dict[str, int] = {}
        for row in rows:
            how[row["repair"]["how"]] = how.get(row["repair"]["how"], 0) + 1
        changed = sum(row["repair"]["chosen"] != 0 for row in rows)
        summary = {"questions": len(rows), "changed": changed, "how": how}
    elif args.command == "deliver":
        if args.executed and (args.candidates or args.selected or args.all):
            parser.error("deliver --executed takes no --candidates, --selected, or --all")
        if not args.executed and not (args.candidates and args.selected):
            parser.error("deliver needs --candidates and --selected, or --executed")
        requests = {r["id"]: r for r in _load(args.requests)}
        try:
            if args.executed:
                executed = _load(args.executed)
                rows = executed_delivery_requests(executed, requests)
                summary = {"records": len(executed), "without_plan": len(executed) - len(rows)}
                inputs = [args.executed, args.requests]
            else:
                rows = delivery_requests(
                    _load(args.candidates), _load(args.selected), requests, every=args.all
                )
                summary = {"all": args.all}
                inputs = [args.candidates, args.selected, args.requests]
        except ValueError as error:
            raise SystemExit(str(error)) from None
        _write(args.out, rows)
        summary["delivered"] = len(rows)
    elif args.command == "merge":
        delivered = {r["id"]: r for r in _load(args.delivered)}
        generated = {r["id"]: r for r in _load(args.generated)}
        try:
            if args.executed:
                rows = merged_executed(_load(args.executed), delivered, generated)
            else:
                rows = merged_records(_load(args.selected), delivered, generated)
        except ValueError as error:
            raise SystemExit(str(error)) from None
        _write(args.out, rows)
        delivery: dict[str, int] = {}
        for row in rows:
            how = row["delivery"] if args.executed else row["repair"]["delivery"]
            delivery[how] = delivery.get(how, 0) + 1
        summary = {"questions": len(rows), "delivery": delivery}
        inputs = [args.executed or args.selected, args.delivered, args.generated]
    else:
        from xgraph.mintqa_bench import dataset_rows

        answers = {qid: row["answer"] for qid, row in dataset_rows(args.split).items()}
        questions = json.loads(args.questions.read_text(encoding="utf-8"))
        groups = {q["id"]: hops(q.get("complexity", "")) for q in questions}
        asked = {q["id"]: answers[q["id"]] for q in questions}
        summary = oracle(_load(args.candidates), asked, groups, args.shortlist)
        inputs = [args.candidates, args.questions]
    summary = {"artifact_kind": f"xgraph.repair.{args.command}", "version": 1, **summary}
    summary["provenance"] = provenance(inputs)
    summary.update(timer.summary())
    target = args.out if args.command == "oracle" else Path(f"{args.out}.summary.json")
    target.write_text(json.dumps(summary, indent=1) + "\n")
    print(json.dumps({k: v for k, v in summary.items() if k != "provenance"}))


def _candidates(args) -> dict:
    from xgraph.index import load_kg_index
    from xgraph.kgversions import load_kg_versions
    from xgraph.programs import MatchedExecutor, record_path
    from xgraph.prompts import final_answer
    from xgraph.tokenizer import ServedTokenizer
    from xgraph.toolkg import KGStore, version_stores

    records = _load(args.outputs)
    asked = {r["id"]: r for r in _load(args.requests)} if args.requests else {}
    version_of = {
        r["id"]: r.get("kg_version") or asked.get(r["id"], {}).get("kg_version") for r in records
    }
    named = sorted({v for v in version_of.values() if v})
    if named and not args.kg_versions:
        raise SystemExit(f"records read KG versions {named[:5]}: candidates needs --kg-versions")
    questions = {
        q["id"]: q["utterance"] for q in json.loads(args.questions.read_text(encoding="utf-8"))
    }
    index = load_kg_index(args.index)
    executor = MatchedExecutor(
        index,
        ServedTokenizer.from_file(args.tokenizer),
        versions=load_kg_versions(args.kg_versions, index) if named else None,
        start_rank=args.start_rank,
        unquoted_starts=args.unquoted_starts,
    )
    store = KGStore(args.db)
    stores = version_stores(store, args.kg_versions, named) if named else None
    rows = [tuple(json.loads(line)) for line in args.relations.read_text().splitlines() if line]
    repairer = Repairer(executor, store, rows, edits=args.edits, stores=stores)
    counts: dict[str, int] = {"questions": 0, "with_path": 0, "candidates": 0, "empty": 0}
    kinds: dict[str, int] = dict.fromkeys(KINDS, 0)
    sizes: dict[int, int] = {}

    def built():
        for record in records:
            qid, path = record["id"], record_path(record)
            version = version_of[qid]
            row = {
                "id": qid,
                "question": questions.get(qid, ""),
                "start": path[0] if path else None,
                "kg_version": version,
                "text": record["text"],
                "answer": final_answer(record["text"]),
                "candidates": [],
                "empty": 0,
            }
            if path:
                anchor = asked.get(qid, {}).get("anchor") or None
                found, empty = repairer.candidates(row["question"], *path, anchor, version)
                row["candidates"], row["empty"] = found, empty
                counts["with_path"] += 1
            counts["questions"] += 1
            counts["candidates"] += len(row["candidates"])
            counts["empty"] += row["empty"]
            for c in row["candidates"]:
                kinds[c["kind"]] += 1
            sizes[len(row["candidates"])] = sizes.get(len(row["candidates"]), 0) + 1
            yield row

    _write(args.out, built())
    return {
        **counts,
        "edits": args.edits,
        "by_kind": kinds,
        "questions_by_candidates": dict(sorted(sizes.items())),
    }


